let failures = 0;
const check = (label, actual, expected) => {
  const ok = JSON.stringify(actual) === JSON.stringify(expected);
  if (!ok) { failures++; console.log(`FAIL ${label}: got ${JSON.stringify(actual)}, want ${JSON.stringify(expected)}`); }
  else console.log(`ok   ${label}`);
};

// dumpPlex's stored checksum (0x30) is wrong in the original Java source —
// the correct value over its data bytes is 0x2E. We assert we detect that,
// and that our round-trip produces the *corrected* checksum.
for (const [name, dump, csumValid, csum] of [['dump1', dump1, true, 0x67], ['dumpPlex', dumpPlex, false, 0x2e]]) {
  const ev = parse(dump);
  check(`${name} parses as dump`, ev.kind, 'dump');
  const p = ev.patch;
  check(`${name} checksum valid`, p.checksumOk, csumValid);
  const rt = p.toDump();
  check(`${name} round-trip identical (modulo corrected checksum)`,
    [...rt].map((b, i) => (i === 274 ? null : b)), [...dump].map((b, i) => (i === 274 ? null : b)));
  check(`${name} regenerated checksum`, rt[274], csum);

  const ydp = patchToYdp(p);
  const back = patchFromYdp(ydp);
  check(`${name} YDP round-trip name`, back.name, p.name);
  check(`${name} YDP round-trip payload`, [...back.payload], [...p.payload]);
}

