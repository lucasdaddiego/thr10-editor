check('Hz Thru inverse', delayP.find(pr => pr.key === 'lowcut').inv('Thru'), 21);
check('Hz numeric inverse', delayP.find(pr => pr.key === 'highcut').inv('4000 Hz'), 4000);
check('tenths inverse', KNOBS[0].inv('3.6'), 36);

// --- hex console parsing
check('parseHex spaced', [...parseHex('F0 43 7d f7')], [0xF0, 0x43, 0x7D, 0xF7]);
check('parseHex run-together', [...parseHex('F0437DF7')], [0xF0, 0x43, 0x7D, 0xF7]);
check('parseHex 0x prefixes and commas', [...parseHex('0xF0, 0x43')], [0xF0, 0x43]);
check('parseHex empty', parseHex('').length, 0);
let hexThrew = false;
try { parseHex('F0 GG'); } catch { hexThrew = true; }
check('parseHex bad byte throws', hexThrew, true);

console.log(failures ? `\n${failures} FAILURES` : '\nALL CHECKS PASSED');
