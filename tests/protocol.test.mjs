// --- .YDL library round-trip (PROTOCOL.md §8.2)
const libIn = new Array(YDL_SLOTS).fill(null);
libIn[0] = parse(dump1).patch;
libIn[42] = parse(dumpPlex).patch;
const ydl = libraryToYdl(libIn);
check('YDL file size', ydl.length, YDL_SIZE);
check('YDL header', [...ydl.subarray(0, 7)], [0x44, 0x54, 0x41, 0x42, 0x30, 0x31, 0x64]);
const libOut = libraryFromYdl(ydl);
check('YDL empty slots stay empty', libOut.filter(Boolean).length, 2);
check('YDL slot 0 name', libOut[0].name, 'Custom Class-A Combo');
check('YDL slot 0 payload', [...libOut[0].payload], [...libIn[0].payload]);
check('YDL slot 42 round-trip', libOut[42].equals(libIn[42]), true);
let ydlThrew = false;
try { libraryFromYdl(ydl.subarray(0, 100)); } catch { ydlThrew = true; }
check('YDL wrong size throws', ydlThrew, true);

// --- clone / equals
const pc = parse(dump1).patch;
const pcClone = pc.clone();
check('clone equals original', pcClone.equals(pc), true);
pcClone.payload[3] = 99;
check('clone is independent', pcClone.equals(pc), false);

// --- model label tables
